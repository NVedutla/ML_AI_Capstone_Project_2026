# RL QUERY (Module 24)
# =========================================================
def rl_query(X, y, dim, epsilon=0.1):

    X = np.array(X, dtype=float)
    y = np.array(y, dtype=float)

    n = min(len(X), len(y))
    X, y = X[:n], y[:n]

    if n < 3:
        return np.random.rand(dim)

    X = X[:, :dim]

    # reward shaping
    y_shift = y - np.min(y)
    if np.sum(y_shift) == 0:
        w = np.ones(len(y)) / len(y)
    else:
        w = y_shift / np.sum(y_shift)

    centroid = np.average(X, axis=0, weights=w)

    # PCA direction
    X_top = X[y >= np.percentile(y, 75)]
    if len(X_top) < 2:
        X_top = X

    pca = PCA(n_components=1)
    pca.fit(X_top)

    direction = pca.components_[0]

    best = X[np.argmax(y)]
    if np.dot(direction, best - centroid) < 0:
        direction = -direction

    step = 0.03
    x_new = centroid + step * direction

    # epsilon exploration
    if np.random.rand() < epsilon:
        x_new += np.random.normal(0, 0.02, dim)

    return np.clip(x_new, 0, 1)


